// tools/build-standalone.mjs — regenerate standalone.html.
//
// BreatheEasy's normal entry point is index.html, which loads styles.css,
// aqi.js and app.js as separate files (that is what GitHub Pages serves,
// and it keeps the code reviewable as separate modules with tests).
// Some viewers open index.html on its own without its sibling files, so
// the page renders as plain unstyled HTML. This script inlines everything
// into one self-contained file that renders correctly however it is opened.
//
// Usage: node tools/build-standalone.mjs
// Output: standalone.html (same folder). Regenerate after any change to
// index.html, styles.css, aqi.js or app.js.
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const dir = dirname(fileURLToPath(import.meta.url));
const root = join(dir, '..');

const html = readFileSync(join(root, 'index.html'), 'utf8');
const css = readFileSync(join(root, 'styles.css'), 'utf8');
const aqiJs = readFileSync(join(root, 'aqi.js'), 'utf8');
const appJs = readFileSync(join(root, 'app.js'), 'utf8');

for (const [name, src] of [['aqi.js', aqiJs], ['app.js', appJs]]) {
  if (src.includes('</script>')) {
    throw new Error(`${name} contains "</script>" and cannot be inlined safely`);
  }
}

let out = html
  .replace(
    '<link rel="stylesheet" href="styles.css">',
    `<!-- Styles inlined by tools/build-standalone.mjs (source: styles.css) -->\n  <style>\n${css}\n  </style>`,
  )
  .replace(
    '<script src="aqi.js"></script>',
    `<!-- Logic inlined by tools/build-standalone.mjs (source: aqi.js) -->\n  <script>\n${aqiJs}\n  </script>`,
  )
  .replace(
    '<script src="app.js"></script>',
    `<!-- UI inlined by tools/build-standalone.mjs (source: app.js) -->\n  <script>\n${appJs}\n  </script>`,
  )
  // The inlined scripts need 'unsafe-inline'; the multi-file index.html
  // keeps the stricter CSP (script-src 'self' only).
  .replace("script-src 'self';", "script-src 'self' 'unsafe-inline';");

out = out.replace(
  '<!-- Defence in depth:',
  '<!-- STANDALONE BUILD — generated by tools/build-standalone.mjs. Do not edit directly; edit index.html / styles.css / aqi.js / app.js and re-run the script. -->\n  <!-- Defence in depth:',
);

writeFileSync(join(root, 'standalone.html'), out);
console.log('standalone.html written');
